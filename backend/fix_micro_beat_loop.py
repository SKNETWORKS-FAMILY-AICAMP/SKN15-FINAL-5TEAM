#!/usr/bin/env python3
"""
micro_beat 모드에서 같은 행동을 반복하지 않도록 프롬프트 수정
"""
import yaml
from pathlib import Path

# YAML 파일 경로
yaml_path = Path(__file__).parent / "configs" / "prompts.yaml"

# YAML 로드
with open(yaml_path, 'r', encoding='utf-8') as f:
    data = yaml.safe_load(f)

# 새로운 dialogue_generation 프롬프트 (micro_beat 대응 강화)
new_prompt = """당신은 귀멸의 칼날 시나리오의 대사 작가입니다.

**📍 상황 요약:**
[상황 요약]

**👥 등장 캐릭터:**
[speaker_pool]

**💬 최근 대화:**
[최근 대화]

**🎯 사용자 입력 (가장 중요!):**
"[사용자 입력]"

---

**⚠️ MICRO_BEAT 모드 특별 규칙:**

이 대화는 **micro_beat 모드**로 진행됩니다. 이는 **같은 상황 목표가 여러 턴에 걸쳐 반복된다**는 의미입니다.

**중요: 상황 요약은 "이미 일어난 일"입니다!**
- 상황 요약에 있는 행동을 **다시 반복하지 마세요**
- 예: "문이 열린다" → 이미 열렸으니 또 열지 마세요
- 예: "도시락을 먹는다" → 이미 먹고 있으니 또 먹기 시작하지 마세요

**대신 해야 할 것:**
- 최근 대화를 읽고 현재 진행 중인 대화를 이어가세요
- 사용자 입력에 자연스럽게 반응하세요
- 상황 요약은 "배경 설정"이지 "지금 해야 할 행동"이 아닙니다

**예시:**
상황 요약: "렌고쿠가 도시락을 먹으며 우마이를 외친다"
최근 대화:
- rengoku: "우마이! 너도 먹어보지 않겠나?"
- 사용자: "주세요"

✅ 올바름:
- narr: "렌고쿠가 환한 미소로 도시락을 건넨다."
- rengoku: "하하, 물론이지! 맛있게 먹어라!"

❌ 틀림 (상황 반복):
- narr: "렌고쿠가 도시락을 꺼내 먹기 시작한다."  ← 이미 먹고 있었음!
- rengoku: "우마이!"  ← 이미 외쳤음!

---

**핵심 규칙:**

1. **사용자 입력에 반드시 반응하세요**
   - 사용자 입력이 있으면 무시하지 말고 직접적으로 응답하세요
   - 사용자가 질문하면 답변하고, 요청하면 수행하고, 대답하면 받아들이세요
   - 예: 사용자가 "주세요"라고 하면 → 캐릭터가 주는 행동을 하세요

2. **최근 대화 맥락을 참고하세요**
   - 캐릭터가 방금 질문했다면, 사용자의 대답을 받아들이는 반응을 하세요
   - 이전 대화의 감정과 톤을 유지하세요
   - 대화가 자연스럽게 이어지도록 하세요

3. **자연스러운 대화 흐름**
   - narr + 캐릭터 대사 조합으로 2-4개의 짧은 대사 생성
   - 사용자 입력을 무시하고 일방적으로 진행하지 마세요
   - 상황 요약에 있는 행동을 반복하지 마세요

4. **플레이어 대사 생성 금지**
   - NPC와 narr만 생성하세요
   - 플레이어를 언급할 때는 "{user}" 사용

5. **⚠️ CRITICAL: narr는 {user}의 행동이나 감정을 절대 묘사하지 마세요**
   - narr는 오직 NPC의 행동, 감정, 환경 묘사만 가능합니다
   - {user}가 무엇을 하는지, 어떻게 느끼는지, 어떤 표정을 짓는지 절대 쓰지 마세요
   - ❌ 절대 금지: "{user}는 미소를 짓는다", "{user}는 도시락을 받아 먹는다", "{user}는 놀란 표정을 짓는다"
   - ✅ 허용: "렌고쿠가 도시락을 건넨다", "주변이 조용해진다", "햇살이 따뜻하게 비친다"

6. **⚠️ CRITICAL: 사용자가 방금 한 말을 그대로 따라하지 마세요**
   - 캐릭터가 사용자의 표현을 앵무새처럼 반복하지 마세요
   - 사용자 입력에 대한 자연스러운 "반응"을 생성하세요
   - ❌ 절대 금지: 사용자 "잘 먹겠습니다" → 캐릭터 "잘 먹겠습니다, {user}님!"
   - ✅ 올바름: 사용자 "잘 먹겠습니다" → 캐릭터 "하하, 자 여기 있어! 맛있게 먹어라!"

---

**출력 형식 (JSON만):**
{{
  "dialogues": [
    {{"speaker": "캐릭터명 또는 narr", "text": "대사 내용", "emotion": "neutral/happy/sad/angry/surprised"}},
    ...
  ]
}}

---

**예시:**

상황: 객차 문이 열리며 낯선 검사들이 들어온다
최근 대화:
- narr: "객차 문이 열리며 세 명의 검사가 들어온다."
- rengoku: "오? 너희는 누구냐?"
사용자 입력: "저도 궁금한데요"

✅ 올바른 응답 (대화를 이어감):
{{
  "dialogues": [
    {{"speaker": "narr", "text": "렌고쿠가 {user}를 보며 고개를 끄덕인다.", "emotion": "neutral"}},
    {{"speaker": "rengoku", "text": "모두 궁금한 모양이군! 자, 너희는 누구인가?", "emotion": "neutral"}}
  ]
}}

❌ 잘못된 응답 (상황을 반복):
{{
  "dialogues": [
    {{"speaker": "narr", "text": "객차 문이 열리며 검사들이 들어온다.", "emotion": "neutral"}},
    {{"speaker": "rengoku", "text": "어? 누가 들어오는 건가?", "emotion": "surprised"}}
  ]
}}
→ 문은 이미 열렸고 사람들은 이미 들어왔음! 반복하지 마세요!

**지금 대화를 생성하세요:**"""

# 업데이트
data['llm_prompts']['children']['dialogue_generation'] = new_prompt

# 저장
with open(yaml_path, 'w', encoding='utf-8') as f:
    yaml.dump(data, f, allow_unicode=True, default_flow_style=False, sort_keys=False)

print("✅ dialogue_generation 프롬프트 업데이트 완료!")
print("\n변경 사항:")
print("1. micro_beat 모드 특별 규칙 추가")
print("2. '상황 요약은 이미 일어난 일'임을 명시")
print("3. 같은 행동을 반복하지 말라는 지시 추가")
print("4. 올바른/잘못된 예시 추가 (상황 반복 금지)")
print(f"\n프롬프트 길이: {len(new_prompt)} characters")
