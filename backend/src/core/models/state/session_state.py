"""
Session State - 세션 메타데이터 및 진행 정보
세션의 기본 정보와 진행 상태를 관리
"""

from typing import TypedDict, Optional


class SessionState(TypedDict):
    """
    세션 메타데이터 및 진행 정보
    - 세션 식별자
    - 사용자 정보
    - 타임스탬프
    - 진행 횟수
    """

    # ============================================================
    # 세션 식별
    # ============================================================
    session_id: str  # 세션 고유 ID
    scenario_id: str  # 현재 시나리오 ID

    # ============================================================
    # 진행 상태
    # ============================================================
    turn_count: int  # 전체 턴 수
    is_timeout: bool  # 타임아웃 여부
    current_node_name: str  # 현재 노드 이름 (예: "CUTSCENE_5_INTRO")
    current_scene_id: str  # 현재 씬 ID

    # ============================================================
    # 사용자 정보
    # ============================================================
    user_name: str  # 사용자 이름

    # ============================================================
    # 메타데이터
    # ============================================================
    meta: dict  # 추가 메타데이터 (timestamp, version, processed_by 등)
